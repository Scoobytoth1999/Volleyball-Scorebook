from playwright.sync_api import sync_playwright
URL='file:///home/claude/volleyball-scorebook/cranbrook/Volleyball_Scorebook.html'
with sync_playwright() as p:
    b=p.chromium.launch(); pg=b.new_page(viewport={'width':1024,'height':768}, accept_downloads=True)
    errs=[]; pg.on('pageerror',lambda e:errs.append(str(e)))
    pg.goto(URL); pg.click('[data-act=new]'); pg.fill('#f-home','Cranbrook'); pg.fill('#f-away','Rice'); pg.click('button[type=submit]')
    pg.click('[data-act=kp][data-team=A][data-k="0"]')
    for n in ['5','3','13','7','9','21','2','8','15','4','10','17']:   # typo: 13 should be 12
        for ch in n: pg.click(f'#kp [data-key="{ch}"]')
        pg.click('#kp [data-key=next]')
    pg.click('button[type=submit]'); pg.click('[data-act=startset]')
    for t in 'AABBA': pg.wait_for_timeout(360); pg.click(f'[data-act=point][data-team={t}]')
    pg.click('[data-act=sub][data-team=A]'); pg.click('[data-act=subout][data-num="13"]'); pg.click('.keys.inline [data-key="1"]'); pg.click('.keys.inline [data-key="4"]'); pg.click('[data-act=dosub]')
    for t in 'BA': pg.wait_for_timeout(360); pg.click(f'[data-act=point][data-team={t}]')
    pg.screenshot(path='el_before.png')
    pg.click('[data-act=editlu]')
    pg.click('[data-act=elsel][data-team=A][data-k="2"]'); pg.click('.keys.inline [data-key=back]'); pg.click('.keys.inline [data-key="2"]')
    # swap B spots I and II (2 and 8)
    pg.click('[data-act=elsel][data-team=B][data-k="0"]'); pg.click('[data-act=elswap]'); pg.click('[data-act=elsel][data-team=B][data-k="1"]')
    pg.click('[data-act=elsel][data-team=A][data-k="2"]')
    pg.screenshot(path='el_modal.png')
    pg.click('[data-act=elsave]'); pg.wait_for_timeout(200)
    print('toast', pg.inner_text('#toast'))
    pg.screenshot(path='el_after.png'); pg.click('[data-act=close]')
    pg.click('[data-act=log]'); print('log first rows', pg.locator('button.logrow').first.inner_text().replace('\n',' | '))
    pg.click('[data-act=close]'); pg.click('[data-act=menu]')
    with pg.expect_download() as d: pg.click('.menulist [data-act=pdf]')
    d.value.save_as('el.pdf')
    print('errors', errs); b.close()
